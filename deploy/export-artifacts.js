#!/usr/bin/env node
/**
 * Extracts the ABI + deploy bytecode that forge produced into deploy/artifacts/,
 * so deploy.js and the MetaMask page consume exactly the compiled output rather
 * than a hand-maintained copy that could drift from src/.
 *
 *   forge build && node deploy/export-artifacts.js
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const OUT  = path.join(ROOT, 'deploy', 'artifacts');

function extract(contract, file) {
  const p = path.join(ROOT, 'out', file, `${contract}.json`);
  if (!fs.existsSync(p)) {
    console.error(`missing ${p}\nRun \`forge build\` first.`);
    process.exit(1);
  }
  const a = JSON.parse(fs.readFileSync(p, 'utf8'));
  const bytecode = a.bytecode?.object;
  if (!bytecode || bytecode === '0x') {
    console.error(`${contract} has no deploy bytecode`);
    process.exit(1);
  }
  return {
    contractName: contract,
    abi: a.abi,
    bytecode,
    // Which optimizer settings produced this. The deploy paths surface it so a
    // deployment can never be silently made from a build that was not tested.
    profile: process.env.FOUNDRY_PROFILE || 'default',
    builtAt: new Date().toISOString(),
  };
}

fs.mkdirSync(OUT, { recursive: true });
const loan = extract('ObscuraLoan', 'ObscuraLoan.sol');

fs.writeFileSync(path.join(OUT, 'ObscuraLoan.json'), JSON.stringify(loan, null, 2));

// Browser-consumable copy: no fetch(), no CORS, works from file://
fs.writeFileSync(
  path.join(OUT, 'ObscuraLoan.artifact.js'),
  `// Generated by deploy/export-artifacts.js - do not edit.\n` +
  `window.OBSCURA_LOAN_ARTIFACT = ${JSON.stringify(loan)};\n`
);

const sizeKb = (loan.bytecode.length / 2 - 1) / 1024;
console.log(`ObscuraLoan  ABI entries: ${loan.abi.length}`);
console.log(`ObscuraLoan  init bytecode: ${sizeKb.toFixed(2)} KB`);
console.log(`ObscuraLoan  built with profile: ${loan.profile}`);
if (loan.profile !== 'production') {
  console.warn('\n\x1b[33mwarning\x1b[0m  Artifact built with the "%s" profile.', loan.profile);
  console.warn('         Deployments should use the production build:');
  console.warn('         FOUNDRY_PROFILE=production forge build && node deploy/export-artifacts.js\n');
}
console.log(`written -> deploy/artifacts/`);
